<?php

use App\Models\User;
use Illuminate\Foundation\Testing\RefreshDatabase;

// Инструмент очистки базы данных перед тестом
uses(RefreshDatabase::class);

test('доступ авторизованного пользователя к главной странице', function () {
    // 1. ПОДГОТОВКА: Создаем в базе одного фейкового пользователя через фабрику
    $user = User::factory()->create();

    // 2. ДЕЙСТВИЕ: Робот логинится под этим пользователем и пытается зайти на Dashboard
    $response = $this->actingAs($user)
        ->get(route('dashboard'));

    // 3. ПРОВЕРКА: Сервер должен вернуть статус 200 OK (успешный вход)
    // Также мы проверяем, видит ли пользователь приветственное слово интерфейса
    $response->assertStatus(200)
        ->assertSee('Користувач'); // Замените 'Dashboard' на любое слово, которое железно есть на вашей главной (например, 'Головна')
});
